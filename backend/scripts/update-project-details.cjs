const prisma = new PrismaClient({
  adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }),
});

async function main() {
  const projects = await prisma.project.findMany({
    select: { id: true, title: true, link: true },
    orderBy: { id: 'asc' },
  });

  const unknownProjects = projects.filter((project) => !projectDetails[project.link]);
  if (unknownProjects.length > 0 || projects.length !== Object.keys(projectDetails).length) {
    throw new Error('Список проектов в базе не совпадает со списком подготовленных данных. Изменения не внесены.');
  }

  if (process.argv.includes('--dry-run')) {
    console.log('Проверка пройдена: будет обновлено работ:', projects.length);
    return;
  }

  await prisma.$transaction(
    projects.map((project) =>
      prisma.project.update({
        where: { id: project.id },
        data: projectDetails[project.link],
      }),
    ),
  );

  console.log('Обновлено работ:', projects.length);
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
